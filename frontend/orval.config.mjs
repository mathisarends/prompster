import { readFileSync } from "node:fs";
import { readFile, rename, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { defineConfig } from "orval";
import * as prettier from "prettier";

import { renderApi } from "./scripts/render-api.mjs";
import { renderQueryFiles } from "./scripts/render-queries.mjs";

const frontendRoot = fileURLToPath(new URL(".", import.meta.url));
const specPath = resolve(frontendRoot, process.env.OPENAPI_SPEC_PATH ?? "openapi.json");

export const outputRoot = resolve(
  frontendRoot,
  process.env.ORVAL_OUTPUT_ROOT ?? "src/api/generated",
);

// Resolved against this file: the drift check writes the client outside the frontend tree.
const prettierOptions = await prettier.resolveConfig(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(specPath, "utf8"));
export const generatedHeader = [
  "/**",
  " * Generated by orval",
  " * Do not edit manually.",
  ` * ${spec.info.title}`,
  ` * OpenAPI spec version: ${spec.info.version}`,
  " */",
].join("\n");
const methods = new Set(["get", "put", "post", "delete", "options", "head", "patch", "trace"]);
const tagNames = new Set();
const operationsByTag = new Map();

for (const [path, pathItem] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(pathItem)) {
    if (!methods.has(method)) {
      continue;
    }
    if (operation.tags?.length !== 1) {
      throw new Error(`${method.toUpperCase()} ${path} needs exactly one OpenAPI tag`);
    }
    const [tag] = operation.tags;
    if (!/^[a-z][a-z0-9_-]*$/.test(tag)) {
      throw new Error(`OpenAPI tag cannot be used as a feature directory: ${tag}`);
    }
    if (tag === "system") {
      continue;
    }
    tagNames.add(tag);
    const name = operation.operationId.replace(/_([a-z0-9])/g, (_, character) =>
      character.toUpperCase(),
    );
    const operations = operationsByTag.get(tag) ?? new Map();
    operations.set(name, {
      path,
      method,
      hasQuery: [...(pathItem.parameters ?? []), ...(operation.parameters ?? [])].some(
        (parameter) => parameter.in === "query",
      ),
    });
    operationsByTag.set(tag, operations);
  }
}

export const tags = [...tagNames].sort();

async function formatFile(path, source) {
  await writeFile(
    path,
    await prettier.format(source, { ...prettierOptions, parser: "typescript" }),
  );
}

async function colocateFeature(featureDir, operations, tag) {
  const apiPath = join(featureDir, "api.ts");
  const generatedModelsPath = join(featureDir, "api.schemas.ts");
  const modelsPath = join(featureDir, "models.ts");
  const apiSource = await readFile(apiPath, "utf8");
  const renderedApi = renderApi(apiSource, operations, generatedHeader);
  await formatFile(apiPath, renderedApi);
  await rename(generatedModelsPath, modelsPath);
  const modelsSource = await readFile(modelsPath, "utf8");
  if (!/^\/\*\*[\s\S]*?\*\//.test(modelsSource)) {
    throw new Error(`Missing generated header in ${modelsPath}`);
  }
  await formatFile(modelsPath, modelsSource.replace(/^\/\*\*[\s\S]*?\*\//, generatedHeader));
  const { queries, mutations } = renderQueryFiles(tag, operations, renderedApi, generatedHeader);
  if (queries) {
    await formatFile(join(featureDir, "queries.ts"), queries);
  }
  if (mutations) {
    await formatFile(join(featureDir, "mutations.ts"), mutations);
  }
  await formatFile(
    join(featureDir, "index.ts"),
    `${generatedHeader}\n\nexport * from "./api";\nexport * from "./models";\n${queries ? 'export * from "./queries";\n' : ""}${mutations ? 'export * from "./mutations";\n' : ""}export { ApiError } from "../../request";\nexport type { ApiProblem, ApiRequestOptions } from "../../request";\n`,
  );
}

export default defineConfig(
  Object.fromEntries(
    tags.map((tag) => {
      const featureDir = join(outputRoot, tag.replaceAll("_", "-"));
      return [
        tag,
        {
          input: { target: specPath, filters: { tags: [tag] } },
          output: {
            mode: "split",
            target: join(featureDir, "api.ts"),
            schemas: false,
            client: "fetch",
            override: {
              mutator: { path: "./src/api/request.ts", name: "apiFetch" },
              fetch: {
                includeHttpResponseReturnType: false,
                forceSuccessResponse: true,
              },
            },
          },
          hooks: {
            afterAllFilesWrite: () => colocateFeature(featureDir, operationsByTag.get(tag), tag),
          },
        },
      ];
    }),
  ),
);
